#!/usr/bin/env python3
"""Regenerate lib/brand/icons.dart from the Phosphor glyphs the app uses.

phosphor_flutter's Dart classes extend IconData, which the newest Flutter forbids, so the app never imports the package.
Its fonts still work: this script copies the codepoints for just the icons referenced in lib/ into a local file.
Run from app/ after using a new PhosphorIconsRegular/Bold/Fill/Duotone.<name>.
"""
import glob, os, re, sys
PKG = glob.glob(os.path.expanduser('~/.pub-cache/hosted/pub.dev/phosphor_flutter-*/lib/src/'))[0]
FAMILY = {'Regular': 'PhosphorRegular', 'Bold': 'PhosphorBold', 'Fill': 'PhosphorFill', 'Duotone': 'PhosphorRegular'}  # duotone drawn as regular
used = {}
for f in glob.glob('lib/**/*.dart', recursive=True):
    if f.endswith('brand/icons.dart'):
        continue
    for m in re.finditer(r'PhosphorIcons(Regular|Bold|Fill|Duotone)\.(\w+)', open(f).read()):
        used.setdefault(m.group(1), set()).add(m.group(2))

def codepoint(style, name):
    for st in ([style] if style != 'Duotone' else ['Duotone', 'Regular']):
        m = re.search(r'static const ' + name + r' = \w+\(0x([0-9a-f]+)', open(f'{PKG}phosphor_icons_{st.lower()}.dart').read())
        if m:
            return m.group(1)

out = ["// Generated by tool/gen_icons.py. Do not edit.\nimport 'package:flutter/widgets.dart';\n"]
missing = []
for style in ['Regular', 'Bold', 'Fill', 'Duotone']:
    out.append(f"\nclass PhosphorIcons{style} {{\n  const PhosphorIcons{style}();")
    for n in sorted(used.get(style, [])):
        cp = codepoint(style, n)
        if cp is None:
            missing.append(f'{style}.{n}'); continue
        out.append(f"  static const IconData {n} = IconData(0x{cp}, fontFamily: '{FAMILY[style]}', fontPackage: 'phosphor_flutter', matchTextDirection: true);")
    out.append("}")
open('lib/brand/icons.dart', 'w').write("\n".join(out) + "\n")
print('icons:', {k: len(v) for k, v in used.items()}, 'missing:', missing)
sys.exit(1 if missing else 0)
